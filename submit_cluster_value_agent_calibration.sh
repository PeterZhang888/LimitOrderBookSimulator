def valid_date(value: object, label: str) -> str:
    if not isinstance(value, str):
        fail(f"{label} is not a string")
    try:
        date.fromisoformat(value)
    except ValueError:
        fail(f"{label} is not ISO YYYY-MM-DD: {value!r}")
    return value

def valid_path(value: object, label: str, *, directory: bool = False) -> str:
    if not isinstance(value, str) or not value:
        fail(f"{label} is missing")
    if "\n" in value or "\r" in value or "\t" in value:
        fail(f"{label} contains an unsupported control character")
    path = pathlib.Path(value).expanduser().resolve()
    if directory:
        if not path.is_dir():
            fail(f"{label} is not a directory: {path}")
    elif not path.is_file():
        fail(f"{label} is not a regular file: {path}")
    return str(path)

def verify_sha256(path_value: str, recorded: object, label: str) -> None:
    if not isinstance(recorded, str) or len(recorded) != 64 \
            or any(character not in "0123456789abcdefABCDEF" for character in recorded):
        fail(f"{label} has no valid recorded SHA-256")
    digest = hashlib.sha256()
    with pathlib.Path(path_value).open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(block)
    observed = digest.hexdigest()
    if observed.lower() != recorded.lower():
        fail(
            f"{label} SHA-256 mismatch: manifest={recorded.lower()} "
            f"observed={observed} path={path_value}"
        )

def runtime_targets(path_value: str, label: str) -> dict[str, tuple[str, ...]]:
    path = pathlib.Path(path_value)
    try:
        with path.open(newline="", encoding="utf-8") as source:
            reader = csv.DictReader(source)
            fields = list(reader.fieldnames or [])
            rows = list(reader)
    except OSError as error:
        fail(f"cannot read {label}: {error}")
    if fields != runtime_fields or not rows:
        fail(f"{label} does not use runtime schema version 5")
    result: dict[str, tuple[str, ...]] = {}
    for line_number, row in enumerate(rows, start=2):
        symbol = str(row.get("symbol", "")).strip().upper()
        if not symbol or symbol in result:
            fail(f"{label} has an invalid symbol at line {line_number}")
        values: list[str] = []
        for field in frozen_training_derived_fields:
            rendered = str(row.get(field, "")).strip()
            try:
                number = float(rendered)
            except ValueError:
                fail(f"{label}:{line_number}:{field} is not numeric")
            if not math.isfinite(number):
                fail(f"{label}:{line_number}:{field} must be finite")
            if (field in latent_value_fields
                    and field != "fundamental_conditional_kurtosis"
                    and number < 0.0):
                fail(f"{label}:{line_number}:{field} must be non-negative")
            if (field == "fundamental_move_probability_per_second"
                    and number > 1.0):
                fail(f"{label}:{line_number}:{field} must not exceed one")
            if (field == "fundamental_conditional_kurtosis"
                    and number < 1.0):
                fail(f"{label}:{line_number}:{field} must be at least one")
            if field not in latent_value_fields and number <= 0.0:
                fail(f"{label}:{line_number}:{field} must be positive")
            values.append(rendered)
        result[symbol] = tuple(values)
    return result

def runtime_rate_paths(path_value: str, label: str) -> dict[str, str]:
    path = pathlib.Path(path_value)
    try:
        with path.open(newline="", encoding="utf-8") as source:
            reader = csv.DictReader(source)
            fields = list(reader.fieldnames or [])
            rows = list(reader)
    except OSError as error:
        fail(f"cannot read {label}: {error}")
    if fields != runtime_fields or not rows:
        fail(f"{label} does not use runtime schema version 5")
    result: dict[str, str] = {}
    for line_number, row in enumerate(rows, start=2):
        symbol = str(row.get("symbol", "")).strip().upper()
        if not symbol or symbol in result:
            fail(f"{label} has an invalid symbol at line {line_number}")
        result[symbol] = valid_path(
            row.get("hawkes_rates_file"),
            f"{label}:{line_number}:hawkes_rates_file",
        )
    return result

def verify_rate_derivation(
    value: object,
    *,
    generated_path: str,
    generated_sha256: object,
    label: str,
    manifest_path: str | None = None,
    manifest_sha256: object = None,
) -> None:
    if not isinstance(value, dict):
        fail(f"{label} lacks rate_derivation")
    maximum_error = value.get(
        "maximum_absolute_stationary_reconstruction_error"
    )
    observed_error = value.get("maximum_absolute_observed_rate_error")
    target_error = value.get("maximum_absolute_stationary_target_error")
    reported_error = value.get(
        "maximum_absolute_reported_reconstruction_error"
    )
    manifest_duration = value.get("manifest_duration_seconds")
    if (
            value.get("schema_version") != 1
            or value.get("status") != "passed"
            or value.get("event_types_checked") != 6
            or isinstance(manifest_duration, bool)
            or not isinstance(manifest_duration, int)
            or manifest_duration <= 0
            or value.get("relative_tolerance") != 1.0e-12
            or value.get("absolute_tolerance") != 1.0e-12
            or value.get(
                "stationary_reconstruction_equals_target_per_type"
            ) is not True
            or value.get(
                "observed_rates_equal_manifest_counts_per_duration"
            ) is not True
            or value.get(
                "stationary_targets_equal_declared_transforms_per_type"
            ) is not True
            or value.get(
                "reported_reconstruction_equals_configured_rate_equation_per_type"
            ) is not True
            or value.get("transform_settings") != expected_hawkes
            or not isinstance(maximum_error, (int, float))
            or not math.isfinite(float(maximum_error))
            or float(maximum_error) < 0.0
            or not isinstance(observed_error, (int, float))
            or not math.isfinite(float(observed_error))
            or not 0.0 <= float(observed_error) <= 1.0e-12
            or not isinstance(target_error, (int, float))
            or not math.isfinite(float(target_error))
            or not 0.0 <= float(target_error) <= 1.0e-12
            or not isinstance(reported_error, (int, float))
            or not math.isfinite(float(reported_error))
            or float(reported_error) < 0.0):
        fail(f"{label} has an incomplete stationary-rate derivation audit")
    manifest = value.get("manifest")
    generated = value.get("generated_hawkes_rates")
    if not isinstance(manifest, dict) or not isinstance(generated, dict):
        fail(f"{label} does not bind its manifest and generated rate file")
    nested_manifest_path = valid_path(
        manifest.get("path"), f"{label} manifest",
    )
    if manifest_path is not None and nested_manifest_path != manifest_path:
        fail(f"{label} rate_derivation names a different source manifest")
    if manifest_sha256 is not None and manifest.get("sha256") != manifest_sha256:
        fail(f"{label} rate_derivation has a conflicting manifest hash")
    verify_sha256(
        nested_manifest_path, manifest.get("sha256"), f"{label} manifest",
    )
    nested_generated_path = valid_path(
        generated.get("path"), f"{label} generated Hawkes rates",
    )
    if nested_generated_path != generated_path:
        fail(f"{label} rate_derivation names a different generated rate file")
    if generated.get("sha256") != generated_sha256:
        fail(f"{label} rate_derivation has a conflicting generated-file hash")
    verify_sha256(
        nested_generated_path,
        generated.get("sha256"),
        f"{label} rate_derivation generated Hawkes rates",
    )

training = payload.get("training_days")
