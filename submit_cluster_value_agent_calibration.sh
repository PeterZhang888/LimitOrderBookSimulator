# Canonical five-session thesis invocation (required):
#
#   sbatch --export=ALL,MULTIDAY_POOLING_PROVENANCE=/shared/pool/pooling_provenance.json,POOLING_PRODUCER_PROJECT_ROOT=/shared/pool-producer-source \
