# the five 2019 training sessions, their individual empirical target roots,
# the pooled training direct inputs, and the 2020-01-30 development-validation
# opening and target source.  That date is not claimed as an independent final
# holdout after this protocol revision.  This script refuses a provenance file
# whose dates do not match the declared five-session protocol.  A legacy
# one-session configuration is intentionally rejected because it cannot carry
# the certified five-day pooled spread/depth feedback targets.
#
# The job deliberately needs one MPI rank at a time: this is compact
# behavioural-policy fitting, not the distributed scaling experiment.  The
# The resulting policy is consumed by the queue-reactive validation and final
# liquidity-shock launchers.
#
# Change literal #SBATCH directives, or override them at submission time.
