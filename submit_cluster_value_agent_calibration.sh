verify_sha256(pooled_config, pooled.get("sha256"), "pooled configuration")
pooled_targets = runtime_targets(pooled_config, "pooled configuration")
pooled_rate_paths = runtime_rate_paths(pooled_config, "pooled configuration")
training_rate_paths = {
    day: runtime_rate_paths(config, f"training config for {day}")
    for day, config, _ in records
}
for day, config, _ in records:
    if runtime_targets(config, f"training config for {day}") != pooled_targets:
        fail(
            f"training config for {day} does not freeze the pooled spread/depth targets"
        )
if runtime_targets(heldout_config, "heldout opening config") != pooled_targets:
    fail(
        "heldout opening config does not freeze the pooled spread/depth targets"
